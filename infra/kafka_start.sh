#!/usr/bin/env bash
# Starts a single-node Kafka broker in KRaft mode: one process is both broker and controller,
# no ZooKeeper. Run it inside WSL2 and keep the terminal open; Ctrl+C stops the broker.
# On the first run, the storage directory is formatted.
#
# Settings (environment variables):
#   KAFKA_HOME      Kafka installation                    (default: ~/kafka)
#   KAFKA_DATA_DIR  broker data, in the Linux filesystem  (default: ~/edge-vlm-data/kafka)
set -euo pipefail

KAFKA_HOME="${KAFKA_HOME:-$HOME/kafka}"
KAFKA_DATA_DIR="${KAFKA_DATA_DIR:-$HOME/edge-vlm-data/kafka}"
CONFIG="$KAFKA_DATA_DIR/server.properties"

if [ ! -x "$KAFKA_HOME/bin/kafka-server-start.sh" ]; then
  echo "Kafka not found in $KAFKA_HOME. Install it (see README) or set KAFKA_HOME." >&2
  exit 1
fi
case "$KAFKA_DATA_DIR" in
  /mnt/*) echo "KAFKA_DATA_DIR must be in the Linux filesystem, not under /mnt." >&2; exit 1 ;;
esac
mkdir -p "$KAFKA_DATA_DIR"

# A second broker on the same data directory rewrites the running broker's controller state before
# it fails on the busy ports, so don't start at all if a broker already listens.
for port in 9092 9093; do
  if (exec 3<>"/dev/tcp/127.0.0.1/$port") 2>/dev/null; then
    echo "Kafka is already running (port $port is in use). Stop it first (Ctrl+C in its terminal)." >&2
    exit 1
  fi
done

# WSL2 forwards a port to Windows only for the address family of the Linux socket, and Java
# listens on IPv6 by default. With IPv4, the broker is reachable from Windows at 127.0.0.1.
# (Windows resolves "localhost" to ::1 first, so all clients use 127.0.0.1 explicitly.)
export KAFKA_OPTS="${KAFKA_OPTS:-} -Djava.net.preferIPv4Stack=true"

# The broker config is written on every start, so this script is the only place to change it.
cat > "$CONFIG" <<EOF
# Generated by infra/kafka_start.sh. Edit the script, not this file.

# This node is the broker and the only KRaft controller.
process.roles=broker,controller
node.id=1
controller.quorum.voters=1@127.0.0.1:9093
controller.listener.names=CONTROLLER

# Clients connect on port 9092 (all interfaces). Advertising 127.0.0.1:9092 works inside WSL2
# and from Windows, through WSL2's localhost forwarding.
listeners=PLAINTEXT://0.0.0.0:9092,CONTROLLER://127.0.0.1:9093
advertised.listeners=PLAINTEXT://127.0.0.1:9092
listener.security.protocol.map=PLAINTEXT:PLAINTEXT,CONTROLLER:PLAINTEXT
inter.broker.listener.name=PLAINTEXT

log.dirs=$KAFKA_DATA_DIR/logs

# A single broker can hold only one replica of Kafka's internal topics.
offsets.topic.replication.factor=1
share.coordinator.state.topic.replication.factor=1
share.coordinator.state.topic.min.isr=1
transaction.state.log.replication.factor=1
transaction.state.log.min.isr=1

# Topics are created explicitly by infra/create_topics.py.
auto.create.topics.enable=false
# Let consumer groups start immediately instead of waiting 3 s for more members.
group.initial.rebalance.delay.ms=0
EOF

if [ ! -f "$KAFKA_DATA_DIR/logs/meta.properties" ]; then
  echo "First run: formatting $KAFKA_DATA_DIR/logs"
  cluster_id="$("$KAFKA_HOME/bin/kafka-storage.sh" random-uuid)"
  "$KAFKA_HOME/bin/kafka-storage.sh" format -t "$cluster_id" -c "$CONFIG"
fi

exec "$KAFKA_HOME/bin/kafka-server-start.sh" "$CONFIG"
